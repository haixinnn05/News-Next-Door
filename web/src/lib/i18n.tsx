const packs: Record<Lang, Pack> = { en, zh, es, fr, ja, hi, ar, ru };

const ids = new Set<string>(LANGS.map((l) => l.id));

function storedLang(): Lang {
  try {
    const saved = localStorage.getItem("btv-lang");
    if (saved && ids.has(saved)) return saved as Lang;
  } catch {
    /* private mode */
  }
  const nav = (navigator.language || "en").toLowerCase();
  const hit = LANGS.find((l) => nav === l.id || nav.startsWith(`${l.id}-`) || (l.id === "zh" && nav.startsWith("zh")));
  return hit?.id ?? "en";
}

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string }>({
  lang: "en",
  setLang: () => {},
  t: (k) => en[k],
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(storedLang);
  useEffect(() => {
    const meta = LANGS.find((l) => l.id === lang)!;
    document.documentElement.lang = meta.html;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);
  const setLang = (l: Lang) => {
    localStorage.setItem("btv-lang", l);
    setLangState(l);
  };
  const t = (k: Key) => packs[lang][k];
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);
